    private void btnKaydolActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKaydolActionPerformed
        String ePosta = txtPosta.getText().trim();
        char[] sifre = txtSifre.getPassword();
        try {
            if (!E_POSTA_DESENI.matcher(ePosta).matches()) {
                JOptionPane.showMessageDialog(rootPane, "Gecerli bir e-posta adresi giriniz.", "Hata", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (sifre.length < 8) {
                JOptionPane.showMessageDialog(rootPane, "Sifre en az 8 karakter olmalidir.", "Hata", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (!chcSozlesme.isSelected() || !chcKvkk.isSelected()) {
                JOptionPane.showMessageDialog(rootPane, "Sozlesme ve KVKK metinlerini kabul etmelisiniz.", "Hata", JOptionPane.ERROR_MESSAGE);
                return;
            }

            JOptionPane.showMessageDialog(rootPane, "Kayit bilgileri gecerli.");
        } finally {
            Arrays.fill(sifre, '\0');
        }
    }//GEN-LAST:event_btnKaydolActionPerformed

